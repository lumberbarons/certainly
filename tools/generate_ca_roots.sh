#!/usr/bin/env bash
# generate_ca_roots.sh — Download root CA PEM files and generate C trust anchors
#
# Usage: Run from the project root: ./tools/generate_ca_roots.sh
# Requires: curl, cc (host C compiler)
# Outputs: src/ca_roots.c

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
BEARSSL_DIR="$PROJECT_ROOT/bearssl"
BRSSL="$BEARSSL_DIR/build/brssl"
CACERTS_DIR="/tmp/cacerts"
OUTPUT="$PROJECT_ROOT/src/ca_roots.c"

echo "==> Building brssl for host..."
mkdir -p "$BEARSSL_DIR/build"
cc -O2 -o "$BRSSL" \
    "$BEARSSL_DIR/tools/brssl.c" \
    "$BEARSSL_DIR/tools/certs.c" \
    "$BEARSSL_DIR/tools/chain.c" \
    "$BEARSSL_DIR/tools/client.c" \
    "$BEARSSL_DIR/tools/errors.c" \
    "$BEARSSL_DIR/tools/files.c" \
    "$BEARSSL_DIR/tools/impl.c" \
    "$BEARSSL_DIR/tools/keys.c" \
    "$BEARSSL_DIR/tools/names.c" \
    "$BEARSSL_DIR/tools/server.c" \
    "$BEARSSL_DIR/tools/skey.c" \
    "$BEARSSL_DIR/tools/sslio.c" \
    "$BEARSSL_DIR/tools/ta.c" \
    "$BEARSSL_DIR/tools/twrch.c" \
    "$BEARSSL_DIR/tools/vector.c" \
    "$BEARSSL_DIR/tools/verify.c" \
    "$BEARSSL_DIR/tools/xmem.c" \
    "$BEARSSL_DIR/src/aead/"*.c \
    "$BEARSSL_DIR/src/codec/"*.c \
    "$BEARSSL_DIR/src/ec/"*.c \
    "$BEARSSL_DIR/src/hash/"*.c \
    "$BEARSSL_DIR/src/int/"*.c \
    "$BEARSSL_DIR/src/kdf/"*.c \
    "$BEARSSL_DIR/src/mac/"*.c \
    "$BEARSSL_DIR/src/rand/"*.c \
    "$BEARSSL_DIR/src/rsa/"*.c \
    "$BEARSSL_DIR/src/ssl/"*.c \
    "$BEARSSL_DIR/src/symcipher/"*.c \
    "$BEARSSL_DIR/src/x509/"*.c \
    "$BEARSSL_DIR/src/settings.c" \
    -I"$BEARSSL_DIR/inc" \
    -I"$BEARSSL_DIR/src"
echo "    brssl built at $BRSSL"

echo "==> Downloading root CA PEM files..."
mkdir -p "$CACERTS_DIR"
curl -sL "https://letsencrypt.org/certs/isrgrootx1.pem"                        -o "$CACERTS_DIR/isrg_root_x1.pem"
curl -sL "https://pki.goog/repo/certs/gtsr1.pem"                               -o "$CACERTS_DIR/google_gts_r1.pem"
curl -sL "https://cacerts.digicert.com/DigiCertGlobalRootG2.crt.pem"           -o "$CACERTS_DIR/digicert_g2.pem"
echo "    PEMs downloaded to $CACERTS_DIR"

echo "==> Generating trust anchors with brssl ta..."
TA_OUTPUT="$("$BRSSL" ta "$CACERTS_DIR"/*.pem)"

cat > "$OUTPUT" <<EOF
/*
 * ca_roots.c — Root CA trust anchor data
 * Auto-generated by tools/generate_ca_roots.sh — do not edit.
 *
 * Sources:
 *   - ISRG Root X1 (Let's Encrypt)
 *   - GTS Root R1 (Google)
 *   - DigiCert Global Root G2
 */

#include "ca_roots.h"

${TA_OUTPUT}

const size_t TAs_NUM = (sizeof TAs) / (sizeof TAs[0]);
EOF

echo "==> Done. Written to $OUTPUT"
